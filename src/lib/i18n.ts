export type Dict = typeof en;
export const dicts: Record<Locale, Dict> = { en, fr };
export const getDict = (l: Locale) => dicts[l];

export function fmtDuration(sec: number) {
  const h = Math.floor(sec / 3600), m = Math.round((sec % 3600) / 60);
  return `${h}h${String(m).padStart(2, "0")}`;
}
export function fmtNum(v: number, locale: Locale, digits = 0) {
  return v.toLocaleString(locale === "fr" ? "fr-FR" : "en-GB", { maximumFractionDigits: digits, minimumFractionDigits: digits });
}
export function fmtDate(iso: string, locale: Locale, opts: Intl.DateTimeFormatOptions = { day: "numeric", month: "short", year: "numeric" }) {
  return new Date(iso + (iso.length === 10 ? "T12:00:00Z" : "")).toLocaleDateString(locale === "fr" ? "fr-FR" : "en-GB", { timeZone: "UTC", ...opts });
}
